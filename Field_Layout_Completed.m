save_all_figures_pdf('Final_Field_Layout_All_Figures.pdf');

function save_all_figures_pdf(pdfname)

figs = findall(0,'Type','figure');
figs = flipud(figs);

if exist(pdfname,'file')
    delete(pdfname)
end

for k = 1:length(figs)
    exportgraphics(figs(k),pdfname, ...
        'Append',true, ...
        'ContentType','vector');
end

fprintf('All figures saved into: %s\n',pdfname);

end